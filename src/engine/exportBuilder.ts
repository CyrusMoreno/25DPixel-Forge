import {
  EngineTarget,
  GeneratedAtlas,
  PaletteTheme,
  StudioMode,
  TilemapConfig,
} from '../types/studio';
import { hexToRgb } from './pixelBuffer';

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadAtlasPng(
  atlas: GeneratedAtlas,
  filename: string,
): Promise<void> {
  return new Promise((resolve) => {
    atlas.canvas.toBlob((blob) => {
      if (blob) {
        triggerDownload(blob, filename);
      }
      resolve();
    }, 'image/png');
  });
}

export function downloadSingleCellPng(
  atlas: GeneratedAtlas,
  x: number,
  y: number,
  width: number,
  height: number,
  filename: string,
): Promise<void> {
  return new Promise((resolve) => {
    const tmp = document.createElement('canvas');
    tmp.width = width;
    tmp.height = height;
    const ctx = tmp.getContext('2d');
    if (ctx) {
      ctx.imageSmoothingEnabled = false;
      ctx.drawImage(atlas.canvas, x, y, width, height, 0, 0, width, height);
    }
    tmp.toBlob((blob) => {
      if (blob) {
        triggerDownload(blob, filename);
      }
      resolve();
    }, 'image/png');
  });
}

export function buildJsonManifest(
  atlas: GeneratedAtlas,
  mode: StudioMode,
  palette: PaletteTheme,
  tileConfig?: TilemapConfig,
): string {
  const payload = {
    generator: 'IsoPixel Forge',
    mode: mode === 'spritesheet' ? 'spritesheet_8dir' : 'isometric_tilemap',
    atlas: {
      width: atlas.width,
      height: atlas.height,
      cellWidth: atlas.cellWidth,
      cellHeight: atlas.cellHeight,
      columns: atlas.columns,
      rows: atlas.rows,
      padding: atlas.padding,
      originX: atlas.originX,
      originY: atlas.originY,
    },
    isometricGrid:
      mode !== 'spritesheet' && tileConfig
        ? {
            tileWidth: tileConfig.tileWidth,
            tileDiamondHeight: tileConfig.tileHeight,
            blockElevation: tileConfig.blockElevation,
          }
        : undefined,
    palette: {
      name: palette.name,
      shades: palette.shades,
    },
    frames: atlas.frames.map((f) => ({
      id: f.id,
      name: f.name,
      x: f.x,
      y: f.y,
      w: f.width,
      h: f.height,
      row: f.row,
      col: f.col,
      direction: f.direction,
      action: f.action,
      frameIndex: f.frameIndex,
    })),
  };
  return JSON.stringify(payload, null, 2);
}

export function downloadJsonManifest(
  atlas: GeneratedAtlas,
  mode: StudioMode,
  palette: PaletteTheme,
  filename: string,
  tileConfig?: TilemapConfig,
): void {
  const json = buildJsonManifest(atlas, mode, palette, tileConfig);
  triggerDownload(new Blob([json], { type: 'application/json' }), filename);
}

export function buildAgkSubimagesTxt(atlas: GeneratedAtlas): string {
  return atlas.frames
    .map((f) => `${f.id}:${f.x}:${f.y}:${f.width}:${f.height}`)
    .join('\n');
}

export function downloadAgkSubimages(
  atlas: GeneratedAtlas,
  filename: string,
): void {
  const content = buildAgkSubimagesTxt(atlas);
  triggerDownload(new Blob([content], { type: 'text/plain' }), filename);
}

export function buildGplPalette(palette: PaletteTheme): string {
  const lines = [
    'GIMP Palette',
    `Name: ${palette.name}`,
    'Columns: 4',
    '# Generated by IsoPixel Forge',
  ];
  const names = ['Highlight', 'Midtone', 'Shadow', 'Deep Outline'];
  palette.shades.forEach((hex, idx) => {
    const { r, g, b } = hexToRgb(hex);
    lines.push(
      `${String(r).padStart(3, ' ')} ${String(g).padStart(3, ' ')} ${String(b).padStart(3, ' ')}\t${names[idx]}`,
    );
  });
  return lines.join('\n') + '\n';
}

export function downloadGplPalette(palette: PaletteTheme): void {
  const slug = palette.name.toLowerCase().replace(/[^a-z0-9]+/g, '_');
  triggerDownload(
    new Blob([buildGplPalette(palette)], { type: 'text/plain' }),
    `${slug}.gpl`,
  );
}

export interface EngineGuideSpec {
  engineName: string;
  specs: Array<{ label: string; value: string }>;
  snippetTitle: string;
  snippetCode: string;
}

export function getEngineGuideSpec(
  engine: EngineTarget,
  mode: StudioMode,
  atlas: GeneratedAtlas,
  tileConfig: TilemapConfig,
): EngineGuideSpec {
  const isSheet = mode === 'spritesheet';

  if (engine === 'godot') {
    if (!isSheet) {
      const originOffsetY = Math.round(
        atlas.cellHeight / 2 - tileConfig.tileHeight / 2,
      );
      return {
        engineName: 'Godot 4 TileMapLayer',
        specs: [
          { label: 'TileShape', value: 'Isometric · Diamond Down' },
          {
            label: 'TileMap tile_size',
            value: `${tileConfig.tileWidth} × ${tileConfig.tileHeight} px`,
          },
          {
            label: 'Texture Region',
            value: `${atlas.cellWidth} × ${atlas.cellHeight} px`,
          },
          {
            label: 'Texture Origin Y',
            value: `${originOffsetY} px`,
          },
        ],
        snippetTitle: 'Godot 4 TileSet Setup (GDScript)',
        snippetCode: `# TileMapLayer Inspector
tile_set.tile_shape = TileSet.TILE_SHAPE_ISOMETRIC
tile_set.tile_layout = TileSet.TILE_LAYOUT_DIAMOND_DOWN
tile_set.tile_size = Vector2i(${tileConfig.tileWidth}, ${tileConfig.tileHeight})

# Atlas Source
source.texture_region_size = Vector2i(${atlas.cellWidth}, ${atlas.cellHeight})
source.separation = Vector2i(${atlas.padding}, ${atlas.padding})`,
      };
    }

    return {
      engineName: 'Godot 4 Sprite2D / AnimatedSprite2D',
      specs: [
        { label: 'Frame Size', value: `${atlas.cellWidth} × ${atlas.cellHeight} px` },
        { label: 'Hframes × Vframes', value: `${atlas.columns} × ${atlas.rows}` },
        { label: 'Offset (Bottom Anchor)', value: `0, -${Math.round(atlas.cellHeight * 0.32)} px` },
        { label: 'Texture Filter', value: 'Nearest (Pixel Crisp)' },
      ],
      snippetTitle: 'Godot 4 Sprite2D Grid Config',
      snippetCode: `# Sprite2D Inspector
hframes = ${atlas.columns}
vframes = ${atlas.rows}
texture_filter = CanvasItem.TEXTURE_FILTER_NEAREST
offset = Vector2(0, -${Math.round(atlas.cellHeight * 0.32)}) # Y-sort feet`,
    };
  }

  if (engine === 'gamemaker') {
    if (!isSheet) {
      return {
        engineName: 'GameMaker Tile Set',
        specs: [
          { label: 'Tile Width × Height', value: `${atlas.cellWidth} × ${atlas.cellHeight} px` },
          { label: 'Grid Separation', value: `${atlas.padding} × ${atlas.padding} px` },
          { label: 'Diamond Step', value: `${tileConfig.tileWidth / 2} × ${tileConfig.tileHeight / 2} px` },
          { label: 'Tile Anchor', value: `${atlas.originX}, ${atlas.originY} px` },
        ],
        snippetTitle: 'GameMaker Iso Grid Helper (GML)',
        snippetCode: `// Isometric grid-to-screen (${tileConfig.tileWidth}x${tileConfig.tileHeight})
var tw = ${tileConfig.tileWidth};
var th = ${tileConfig.tileHeight};
var screen_x = (gx - gy) * (tw * 0.5);
var screen_y = (gx + gy) * (th * 0.5);
// Draw tile anchored at (${atlas.originX}, ${atlas.originY})`,
      };
    }

    return {
      engineName: 'GameMaker Sprite Strip Import',
      specs: [
        { label: 'Cell Size', value: `${atlas.cellWidth} × ${atlas.cellHeight} px` },
        { label: 'Columns × Rows', value: `${atlas.columns} × ${atlas.rows} (${atlas.frames.length} frames)` },
        { label: 'Origin (Bottom-Center)', value: `X: ${atlas.originX}, Y: ${atlas.originY}` },
        { label: 'Interpolation', value: 'Off (Interpolate colors disabled)' },
      ],
      snippetTitle: 'GameMaker Image Import Settings (GML)',
      snippetCode: `// Import -> Convert Frames (${atlas.columns} cols x ${atlas.rows} rows)
// Set Sprite Origin to X=${atlas.originX}, Y=${atlas.originY}
// Depth sort in Step Event:
depth = -y;`,
    };
  }

  // AGK Studio
  if (!isSheet) {
    return {
      engineName: 'AGK Studio SubImage Atlas',
      specs: [
        { label: 'Atlas File', value: 'tilemap.png + tilemap subimages.txt' },
        { label: 'Cell Size', value: `${atlas.cellWidth} × ${atlas.cellHeight} px` },
        { label: 'Iso Step', value: `${tileConfig.tileWidth / 2}, ${tileConfig.tileHeight / 2} px` },
        { label: 'Mag / Min Filter', value: '0 (Nearest Neighbor)' },
      ],
      snippetTitle: 'AGK Studio Tier 1 Loader',
      snippetCode: `atlas = LoadImage("tilemap.png")
SetImageMagFilter(atlas, 0)
SetImageMinFilter(atlas, 0)
tileImg = LoadSubImage(atlas, "${atlas.frames[0]?.id ?? 'ground'}")
spr = CreateSprite(tileImg)
SetSpriteOffset(spr, ${atlas.originX}, ${atlas.originY})`,
    };
  }

  return {
    engineName: 'AGK Studio Sprite Animation',
    specs: [
      { label: 'Atlas File', value: 'spritesheet.png + subimages.txt' },
      { label: 'Frame Bounds', value: `${atlas.cellWidth} × ${atlas.cellHeight} px` },
      { label: 'Total Frames', value: `${atlas.frames.length} (8 dir rows)` },
      { label: 'Sprite Offset', value: `${atlas.originX}, ${atlas.originY} px` },
    ],
    snippetTitle: 'AGK Studio Tier 1 Animated Sprite',
    snippetCode: `sheet = LoadImage("spritesheet.png")
SetImageMagFilter(sheet, 0)
SetImageMinFilter(sheet, 0)
spr = CreateSprite(sheet)
SetSpriteAnimation(spr, ${atlas.cellWidth}, ${atlas.cellHeight}, ${atlas.frames.length})
SetSpriteOffset(spr, ${atlas.originX}, ${atlas.originY})
PlaySprite(spr, 8, 1, 1, ${atlas.columns})`,
  };
}
